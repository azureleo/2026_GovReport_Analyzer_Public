"""M3-2 배출전망 시나리오 결정론 정규화 테스트."""
from __future__ import annotations

from agents.organizer_agent import OrganizerAgent


def _정제(rows: list[dict]) -> list[dict]:
    return OrganizerAgent().organize(
        {"municipality_name": "테스트시", "emissions_forecast": rows}
    )["emissions_forecast"]


def test_배출전망_시나리오를_세_표준계열로_정규화한다() -> None:
    rows = _정제(
        [
            {"시나리오": "총배출량 전망", "부문": "건물", "연도": 2030, "전망값": 10},
            {"시나리오": "현행추세 유지", "부문": "수송", "연도": 2030, "전망값": 20},
            {"시나리오": "온실가스 감축 정책", "부문": "산업", "연도": 2030, "전망값": 30},
            {"시나리오": "정책 반영 목표", "부문": "농업", "연도": 2030, "전망값": 40},
            {"시나리오": "추가 대책 시행", "부문": "폐기물", "연도": 2030, "전망값": 50},
        ]
    )

    assert [row["시나리오"] for row in rows] == [
        "BAU",
        "BAU",
        "정책반영",
        "정책반영",
        "추가조치",
    ]
    assert len(rows) == 5


def test_배출전망_매핑불가_시나리오는_원값을_유지한다() -> None:
    [row] = _정제(
        [{"시나리오": "기준안", "부문": "건물", "연도": 2030, "전망값": 10}]
    )

    assert row["시나리오"] == "기준안"
    assert row.get("전망방법원문", "") == ""


def test_배출전망_정규화_원문은_빈_전망방법원문으로만_이관한다() -> None:
    rows = _정제(
        [
            {"시나리오": "관리권한 배출량 전망", "부문": "건물", "연도": 2030, "전망값": 10},
            {
                "시나리오": "총배출량 전망",
                "전망방법원문": "시계열 분석",
                "부문": "수송",
                "연도": 2030,
                "전망값": 20,
            },
        ]
    )

    assert rows[0]["시나리오"] == "BAU"
    assert rows[0]["전망방법원문"] == "관리권한 배출량 전망"
    assert rows[1]["시나리오"] == "BAU"
    assert rows[1]["전망방법원문"] == "시계열 분석"


def test_배출전망_시나리오는_긴_키워드를_우선한다() -> None:
    rows = _정제(
        [
            {"시나리오": "BAU 대비 31.2% 감축", "부문": "건물", "연도": 2030, "전망값": 10},
            {"시나리오": "추가조치 감축목표", "부문": "수송", "연도": 2030, "전망값": 20},
        ]
    )

    assert [row["시나리오"] for row in rows] == ["정책반영", "추가조치"]
